// Seeded pseudo-random numbers, for scene content that must be the same on every load and in
// every module that reads it (the terrain tile, the intercept burst's pieces).

/** Small seeded PRNG (mulberry32), returns floats in [0, 1). */
export function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
